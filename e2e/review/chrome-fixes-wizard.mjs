// Regression check for the listing wizard: no "Maximum update depth" loop on steps 5+, and typing in the Summary box keeps every letter
// (autosave used to overwrite keystrokes typed while a save was in flight). Stack: web :3014 -> API :4014, account from chrome-fixes-setup.mts.
import { chromium } from "/Users/kazjames/Downloads/activtyos-app-/node_modules/playwright/index.mjs";
import fs from "node:fs";
const A = JSON.parse(fs.readFileSync(process.cwd() + "/e2e/review/chrome-fixes-accounts.json", "utf8"));
const WEB = "http://localhost:3014";
const b = await chromium.launch();
const page = await (await b.newContext({ viewport: { width: 1360, height: 900 } })).newPage();
page.setDefaultTimeout(60000);
const errors = [];
page.on("pageerror", (e) => errors.push(String(e.message)));
page.on("console", (m) => { if (m.type() === "error" && /Maximum update depth/i.test(m.text())) errors.push(m.text().slice(0, 200)); });
await page.goto(WEB + "/login", { waitUntil: "load", timeout: 180000 });
await page.locator('input[type="email"]').first().fill(A.email);
await page.locator('input[type="password"]').first().fill(A.password);
await page.getByRole("button", { name: "Sign in", exact: true }).last().click();
await page.waitForURL((u) => !/login/.test(u.pathname), { timeout: 180000 });
await page.waitForTimeout(3000);
await page.goto(WEB + "/freelancer/blocks", { waitUntil: "load", timeout: 180000 });
await page.getByRole("button", { name: "+ Add a period" }).click();
await page.getByPlaceholder("Period title").fill("Full day");
await page.getByRole("button", { name: "Add period", exact: true }).click();
await page.getByRole("button", { name: "+ Add a pass" }).click();
await page.getByPlaceholder("Pass name (e.g. 5-day week pass)").fill("Day pass");
await page.getByRole("button", { name: "Add pass", exact: true }).click();
const addToBlock = page.getByRole("button", { name: "+ Add to block" });
await page.getByText("Day pass").first().waitFor();
await page.waitForTimeout(1500);
const cc = await addToBlock.count();
for (let i = 0; i < cc; i++) await addToBlock.first().click();
await page.getByPlaceholder("e.g. Summer Multi Activity Camp — Loughton").fill("Loop block");
await page.getByRole("button", { name: /Move to Block Library/ }).click();
const sp = page.getByRole("button", { name: "Save pricing" }).first();
if (await sp.isVisible().catch(() => false)) await sp.click();
await page.goto(WEB + "/freelancer/listings", { waitUntil: "load", timeout: 180000 });
await page.getByRole("button", { name: /New listing/ }).click();
await page.getByPlaceholder("e.g. Summer Multi-Activity Camp").fill("Loop test camp");
await page.getByTitle(/\. Details$/).click();
await page.locator("select").filter({ hasText: "Select a venue…" }).selectOption({ index: 1 });
await page.getByTitle(/\. When it runs$/).click();
await page.getByLabel("Runs from").fill("2027-03-01");
await page.getByLabel("Runs to").fill("2027-03-12");
await page.getByTitle(/\. Tickets & pricing$/).click();
await page.getByRole("button", { name: "Loop block" }).first().click();
await page.getByTitle(/\. Content$/).click();
const ta = page.locator("textarea").first();
await ta.click();
await ta.pressSequentially("testing a long summary typed at human speed", { delay: 90 });
await page.waitForTimeout(3500);
const typed = await ta.inputValue();
console.log("summary kept all letters:", typed === "testing a long summary typed at human speed", JSON.stringify(typed));
for (const t of ["Provided", "Safety & SEND", "When it runs", "Tickets & pricing", "Discounts", "Add-ons", "Staff", "Preview", "Policy & publish"]) {
  await page.getByTitle(new RegExp("\\. " + t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "$")).click();
  await page.waitForTimeout(1200);
  console.log(t, "errors so far:", errors.length);
}
console.log(errors.length ? "FAIL: " + errors.slice(0, 3).join(" | ") : "PASS no update-depth errors");
await b.close();
process.exit(errors.length || false ? 1 : 0);
