#!/usr/bin/env node
// Turns the raw PNG captures (scratch/hiw-raw, from e2e/review/how-it-works-shots.spec.ts) into the compressed WebP screens the
// "How it works" explainers use, and writes features/learninghub/howitworks/shots.gen.ts (name -> src + size + device).
//   node scripts/hiw-optimise.mjs
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const RAW = "scratch/hiw-raw";
const OUT = "public/how-it-works";
const GEN = "features/learninghub/howitworks/shots.gen.ts";
fs.mkdirSync(OUT, { recursive: true });
const rows = {};
for (const f of fs.readdirSync(RAW).filter((x) => x.endsWith(".png")).sort()) {
  const name = f.replace(/\.png$/, "");
  const phone = name.startsWith("k-");
  const img = sharp(path.join(RAW, f));
  const meta = await img.metadata();
  const w = phone ? Math.min(meta.width, 780) : Math.min(meta.width, 2000);
  const out = await img.resize({ width: w }).webp({ quality: phone ? 82 : 76, effort: 5 }).toBuffer({ resolveWithObject: true });
  fs.writeFileSync(path.join(OUT, name + ".webp"), out.data);
  const rp = path.join(RAW, name + ".rects.json");
  if (fs.existsSync(rp)) { // the element rectangles recorded with the capture (rings / zooms / cursors point at these), trimmed to the useful ones
    const all = JSON.parse(fs.readFileSync(rp, "utf8"));
    fs.writeFileSync(path.join(OUT, name + ".rects.json"), JSON.stringify(all.filter((r) => (r.t || r.id) && r.w >= 0.5 && r.h >= 0.5)));
  }
  rows[name] = { src: `/how-it-works/${name}.webp`, w: out.info.width, h: out.info.height, device: phone ? "phone" : "desktop" };
  console.log(name.padEnd(22), `${out.info.width}x${out.info.height}`, `${(out.data.length / 1024).toFixed(0)} KB`);
}
const body = Object.entries(rows).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
fs.writeFileSync(GEN, `// GENERATED by scripts/hiw-optimise.mjs — do not edit. Real screens of the app (see docs/teaching-hub-how-it-works.md).\nexport const SHOTS = {\n${body}\n} as const;\n`);
console.log(`wrote ${GEN} (${Object.keys(rows).length} screens)`);
