// Rebuilds lib/i18n/messages/areas/p8api.ts from scripts/i18n/api-errors/*.json (each file: array of 11-string rows [en, pl, ro, ur, pa, bn, ar, pt, es, fr, cy]).
// usage: server/node_modules/.bin/tsx scripts/i18n/build-api-errors.mjs   (also prints how many extracted server messages still lack a row)
import fs from "node:fs"; import path from "node:path";
import { apiErrorKey } from "../../lib/i18n/apiErrorKey.ts";
import { extract } from "./extract-api-errors.mjs";
const dir = "scripts/i18n/api-errors";
const rows = new Map();
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith(".json")).sort()) for (const r of JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"))) {
  if (r.length !== 11) { console.error(`bad row in ${f}:`, r[0]); process.exit(1); }
  const norm = (s) => s.replace(/\{v\d+\}/g, (m) => m); // keep as is
  rows.set(apiErrorKey(r[0]), r.map(norm));
}
const q = (s) => JSON.stringify(s);
let body = `// p8api: user-facing translations of the API's English error messages (GENERATED by scripts/i18n/build-api-errors.mjs from scripts/i18n/api-errors/*.json: edit those).\n// Keyed by apiErrorKey(english message); rendered by lib/i18n/apiErrors.ts via lib/api.ts. Row order: en, pl, ro, ur, pa, bn, ar, pt, es, fr, cy.\nimport { fromRows } from "./_rows";\n\nexport default fromRows({\n`;
for (const [k, r] of rows) body += `  ${k}: [${r.map(q).join(", ")}],\n`;
body += "});\n";
fs.writeFileSync("lib/i18n/messages/areas/p8api.ts", body);
const all = extract(); const missing = [...all.keys()].filter((m) => !rows.has(apiErrorKey(m)));
console.log(`${rows.size} rows written; ${missing.length} of ${all.size} server messages still untranslated`);
if (process.argv.includes("--list")) fs.writeFileSync(process.env.MISSING_OUT || "/tmp/api-missing.json", JSON.stringify(missing, null, 1));
