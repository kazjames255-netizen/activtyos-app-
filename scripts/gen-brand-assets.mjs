// Regenerates every raster brand asset from public/brand/mark.svg. Run: node scripts/gen-brand-assets.mjs
import sharp from "sharp";
import fs from "node:fs";

const mark = fs.readFileSync("public/brand/mark.svg");
const png = (n) => sharp(mark, { density: Math.max(72, n * 2) }).resize(n, n).png().toBuffer();

for (const n of [192, 512]) fs.writeFileSync(`public/brand/icon-${n}.png`, await png(n));
fs.writeFileSync("app/apple-icon.png", await png(180));
fs.writeFileSync("app/icon.svg", mark);

// favicon.ico = PNG-in-ICO with 16/32/48 frames
const sizes = [16, 32, 48];
const frames = await Promise.all(sizes.map(png));
const head = Buffer.alloc(6 + 16 * sizes.length);
head.writeUInt16LE(1, 2); head.writeUInt16LE(sizes.length, 4);
let off = head.length;
sizes.forEach((s, i) => {
  const o = 6 + i * 16;
  head[o] = s; head[o + 1] = s; head.writeUInt16LE(1, o + 4); head.writeUInt16LE(32, o + 6);
  head.writeUInt32LE(frames[i].length, o + 8); head.writeUInt32LE(off, o + 12); off += frames[i].length;
});
fs.writeFileSync("app/favicon.ico", Buffer.concat([head, ...frames]));
fs.copyFileSync("app/favicon.ico", "public/favicon.ico");

// Social card 1200x630
const inner = mark.toString().replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
const og = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
<rect width="1200" height="630" fill="#0b1f5c"/>
<g transform="translate(110 150) scale(2.4)">${inner}</g>
<text x="400" y="290" font-family="Helvetica,Arial,sans-serif" font-weight="700" font-size="110" letter-spacing="-3" fill="#fff">ActivityLane</text>
<text x="404" y="365" font-family="Helvetica,Arial,sans-serif" font-size="38" fill="#cfd8f6">Bookings, staff, registers and payments for activity providers</text>
<text x="404" y="560" font-family="Helvetica,Arial,sans-serif" font-size="32" font-weight="600" fill="#ffb02e">activitylane.com</text>
</svg>`;
const ogPng = await sharp(Buffer.from(og)).png().toBuffer();
fs.writeFileSync("app/opengraph-image.png", ogPng);
fs.writeFileSync("app/twitter-image.png", ogPng);
fs.writeFileSync("public/brand/og.png", ogPng);
console.log("brand assets written");

// ---- Bare lockups (no tile): the form used on every surface; the tile mark.svg stays for icons only ----
const LANES = '<path d="M16 62H52Q70 62 82 52" stroke="#ff6f91" stroke-width="9" stroke-linecap="round" fill="none"/><path d="M16 76H60Q76 76 86 66" stroke="#18b9a4" stroke-width="9" stroke-linecap="round" fill="none"/><path d="M16 90H68Q82 90 90 80" stroke="#8a6cf2" stroke-width="9" stroke-linecap="round" fill="none"/>';
const figure = (c) => `<circle cx="50" cy="19" r="9" fill="${c}"/><path d="M50 41v10M50 41 37 30M50 41 63 30" stroke="${c}" stroke-width="8" stroke-linecap="round" fill="none"/>`;
const TONES = { dark: { figure: "#ffffff", activity: "#ffffff", lane: "#ffb02e" }, light: { figure: "#14378f", activity: "#14378f", lane: "#c77700" } };
const FONT = "'Bricolage Grotesque','Hanken Grotesk',Helvetica,Arial,sans-serif";
for (const [k, t] of Object.entries(TONES)) {
  const bare = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="9 7 88 90" width="88" height="90" role="img" aria-label="ActivityLane">${figure(t.figure)}${LANES}</svg>`;
  fs.writeFileSync(`public/brand/mark-bare-${k}.svg`, bare + "\n");
  const lock = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 440 90" width="440" height="90" role="img" aria-label="ActivityLane"><g transform="translate(-9 -7)">${figure(t.figure)}${LANES}</g><text x="102" y="62" font-family="${FONT}" font-weight="800" font-size="56" letter-spacing="-1.5"><tspan fill="${t.activity}">Activity</tspan><tspan fill="${t.lane}">Lane</tspan></text></svg>`;
  fs.writeFileSync(`public/brand/logo-${k}.svg`, lock + "\n");
}

// Email marks: bare PNG (transparent) as inline (CID) images. dark = for the blue header band, light = for white/grey footers.
const b64 = {};
for (const k of ["dark", "light"]) {
  b64[k] = (await sharp(fs.readFileSync(`public/brand/mark-bare-${k}.svg`), { density: 400 }).resize({ height: 128 }).png({ compressionLevel: 9 }).toBuffer()).toString("base64");
}
fs.writeFileSync("server/src/lib/brandLogo.ts", `// Generated by scripts/gen-brand-assets.mjs from public/brand/mark-bare-*.svg. Do not edit by hand.\n// Bare mark (no tile). DARK = white figure, for the blue email header; LIGHT = navy figure, for white / light-grey backgrounds.\nexport const AOS_MARK_DARK_PNG_B64 =\n  "${b64.dark}";\nexport const AOS_MARK_LIGHT_PNG_B64 =\n  "${b64.light}";\n`);
console.log("lockups + email marks written");
