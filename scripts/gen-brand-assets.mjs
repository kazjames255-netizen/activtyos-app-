// Regenerates every raster brand asset from public/brand/mark.svg. Run: node scripts/gen-brand-assets.mjs
import sharp from "sharp";
import fs from "node:fs";

const mark = fs.readFileSync("public/brand/mark.svg");
const png = (n) => sharp(mark, { density: Math.max(72, n * 2) }).resize(n, n).png().toBuffer();

for (const n of [192, 512]) fs.writeFileSync(`public/brand/icon-${n}.png`, await png(n));
fs.writeFileSync("app/apple-icon.png", await png(180));
fs.writeFileSync("app/icon.svg", mark);

// favicon.ico = PNG-in-ICO with 16/32/48 frames
const sizes = [16, 32, 48];
const frames = await Promise.all(sizes.map(png));
const head = Buffer.alloc(6 + 16 * sizes.length);
head.writeUInt16LE(1, 2); head.writeUInt16LE(sizes.length, 4);
let off = head.length;
sizes.forEach((s, i) => {
  const o = 6 + i * 16;
  head[o] = s; head[o + 1] = s; head.writeUInt16LE(1, o + 4); head.writeUInt16LE(32, o + 6);
  head.writeUInt32LE(frames[i].length, o + 8); head.writeUInt32LE(off, o + 12); off += frames[i].length;
});
fs.writeFileSync("app/favicon.ico", Buffer.concat([head, ...frames]));
fs.copyFileSync("app/favicon.ico", "public/favicon.ico");

// Social card 1200x630
const inner = mark.toString().replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
const og = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
<rect width="1200" height="630" fill="#0b1f5c"/>
<g transform="translate(110 150) scale(2.4)">${inner}</g>
<text x="400" y="290" font-family="Helvetica,Arial,sans-serif" font-weight="700" font-size="110" letter-spacing="-3" fill="#fff">ActivityLane</text>
<text x="404" y="365" font-family="Helvetica,Arial,sans-serif" font-size="38" fill="#cfd8f6">Bookings, staff, registers and payments for activity providers</text>
<text x="404" y="560" font-family="Helvetica,Arial,sans-serif" font-size="32" font-weight="600" fill="#ffb02e">activitylane.com</text>
</svg>`;
const ogPng = await sharp(Buffer.from(og)).png().toBuffer();
fs.writeFileSync("app/opengraph-image.png", ogPng);
fs.writeFileSync("app/twitter-image.png", ogPng);
fs.writeFileSync("public/brand/og.png", ogPng);
console.log("brand assets written");

// Email mark: inline (CID) PNG used by the server's booking / invite emails
const emailPng = await sharp(mark, { density: 300 }).resize(128, 128).png({ compressionLevel: 9 }).toBuffer();
fs.writeFileSync("server/src/lib/brandLogo.ts", `// Generated by scripts/gen-brand-assets.mjs from public/brand/mark.svg. Do not edit by hand.\nexport const AOS_MARK_PNG_B64 =\n  "${emailPng.toString("base64")}";\n`);
